# Four numbers: find three integers x1, x2, x3 (1 to 10) whose subset sums generate every given number.
import itertools

from pyscipopt import Model, quicksum

# the three unknown integers are between 1 and 10 (problem domain)
VALUE_LB, VALUE_UB = 1, 10
# the three unknowns; a subset of them is any non-empty set of their indices
N_X = 3
SUBSETS = [S for r in range(1, N_X + 1) for S in itertools.combinations(range(N_X), r)]


def build(instance):
    numbers = instance["numbers"]  # up to four numbers, the count comes from the instance
    m = Model()

    x = [m.addVar(name=f"x_{i}", vtype="I", lb=VALUE_LB, ub=VALUE_UB) for i in range(N_X)]

    # y[j, S] = 1 if number j is the sum of the subset S of x
    y = {
        (j, S): m.addVar(name=f"y_{j}_{'_'.join(map(str, S))}", vtype="B")
        for j in range(len(numbers))
        for S in SUBSETS
    }

    for j, n in enumerate(numbers):
        # each number must be generated by some subset of x
        m.addCons(quicksum(y[j, S] for S in SUBSETS) >= 1)
        for S in SUBSETS:
            subset_sum = quicksum(x[i] for i in S)
            # if the subset S is chosen for number j, its sum equals that number
            # (an equality needs two indicators on the same binary)
            m.addConsIndicator(subset_sum >= n, binvar=y[j, S])
            m.addConsIndicator(subset_sum <= n, binvar=y[j, S])

    return m, {"x": x}
