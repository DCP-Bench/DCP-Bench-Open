# Preprocess: compute run boundaries and cumulative counts per run
N = len(a)
counts_by_run = []
if N > 0:
    prev = a[0]
    cnt = 0
    for v in a:
        if v == prev:
            cnt += 1
        else:
            counts_by_run.append(cnt)
            prev = v
            cnt = 1
    counts_by_run.append(cnt)

cum_counts = []
running = 0
for c in counts_by_run:
    running += c
    cum_counts.append(running)

R = len(counts_by_run)  # number of runs
target = int(round(N / k))  # desired group size

# Model definition
model = cp.Model()

# Decision Variables
b = cp.intvar(0, max(0, R - 2), shape=k - 1, name="b")          # run indices where groups end
x = cp.intvar(1, max(1, N - 1), shape=k - 1, name="x")          # 1-based breakpoint positions
sizes = cp.intvar(1, N, shape=k, name="sizes")                  # group sizes

# Constraints
if k == 1:
    model += (sizes[0] == N)
else:
    # strictly increasing breakpoints in element positions
    model += [x[i] < x[i+1] for i in range(k - 2)]
    # optionally, enforce strictly increasing run indices as well
    model += [b[i] < b[i+1] for i in range(k - 2)]
    # link x to run boundaries via Element constraint
    model += [x[i] == cp.Element(cum_counts, b[i]) for i in range(k - 1)]
    # group sizes from breakpoints
    model += (sizes[0] == x[0])
    if k > 2:
        model += [sizes[i] == x[i] - x[i-1] for i in range(1, k - 1)]
    model += (sizes[k - 1] == N - x[k - 2])

# Objective: minimize total absolute deviation from target size
total_error = cp.sum([cp.Abs(sizes[i] - target) for i in range(k)])
model.minimize(total_error)

# Solve and print
