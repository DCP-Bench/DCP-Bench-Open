N = len(a)
# Allowed split positions are between i and i+1 where values differ.
allowed = [i for i in range(1, N) if a[i - 1] != a[i]]  # 1-based indices for break points
L = len(allowed)

# Target group size: round(N/k)
target = int(round(N / k))

# Model definition
model = cp.Model()

# Decision variables:
# t are indices into the allowed split positions array (0..L-1), strictly increasing
t = cp.intvar(0, max(0, L - 1), shape=k - 1, name="t")
# b are the actual break point positions (1-based indices between 1 and N-1)
b = cp.intvar(1, max(1, N - 1), shape=k - 1, name="b")

# Group sizes (positive integers)
s = cp.intvar(1, N, shape=k, name="s")

# Constraints

# Ensure there are enough allowed split positions to make k-1 breaks
if L < k - 1:
    # Infeasible: not enough allowed split points; model will have no solution.
    model += (1 == 2)  # force unsat
else:
    # t strictly increasing (choose distinct allowed positions in order)
    for i in range(k - 2):
        model += (t[i] < t[i + 1])
    # Map t to actual break positions using Element
    for i in range(k - 1):
        model += (b[i] == cp.Element(allowed, t[i]))
    # Define group sizes from breakpoints
    model += (s[0] == b[0])
    for j in range(1, k - 1):
        model += (s[j] == b[j] - b[j - 1])
    model += (s[k - 1] == N - b[k - 2])
    # Sum check (redundant but safe)
    model += (cp.sum(s) == N)

# Objective: minimize total absolute deviation from target
model.minimize(cp.sum([cp.Abs(s[i] - target) for i in range(k)]))

# Solve and print
