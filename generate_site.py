def load_generated_models() -> dict:
    """Scan generated_models/<problem>/<solver>/<submission>/ -> {problem: {solver id: [entries]}}.

    Keyed on the integration id, never on its display name: the name is read
    from `solvers/<id>/metadata.yaml` at render time so renaming an integration
    is a one-line metadata edit, and two integrations sharing a display name
    cannot collapse into one group.
    """
    out = {}
    if not GENERATED_DIR.is_dir():
        return out
    for problem_dir in GENERATED_DIR.iterdir():
        if not problem_dir.is_dir():
            continue
        by_fw = {}
        for fw_dir in problem_dir.iterdir():
            if not fw_dir.is_dir():
                continue
            entries = []
            for sub_dir in sorted(fw_dir.iterdir()):
                if not sub_dir.is_dir():
                    continue
                record_path = sub_dir / "record.json"
                if not record_path.is_file():
                    continue
                try:
                    metrics = json.loads(record_path.read_text(encoding="utf-8"))
                except Exception:
                    continue
                model_file = metrics.get("model_file") or next(
                    (f.name for f in sorted(sub_dir.iterdir())
                     if f.is_file() and f.name.startswith("model.")),
                    None,
                )
                code = ""
                if model_file:
                    try:
                        code = (sub_dir / model_file).read_text(encoding="utf-8")
                    except Exception:
                        code = ""
                entries.append({
                    "submission": sub_dir.name,
                    "directory": fw_dir.name,
                    "metrics": metrics,
                    "model_file": model_file,
                    "code": code,
                })
            if entries:
                solver = entries[0]["metrics"].get("solver") or fw_dir.name
                by_fw[solver] = entries
        if by_fw:
            out[problem_dir.name] = by_fw
    return out


def framework_name(solver_id: str) -> str:
    """What the catalogue calls an integration. Falls back to the id, which is
    what is left when a model outlives the integration that produced it."""
    return (INTEGRATIONS.get(solver_id) or {}).get("name") or solver_id


def verdict_badge(metrics: dict) -> str:
    key = normalize_badge(metrics)
    color, label, tooltip = VERDICT_STYLES.get(key, VERDICT_STYLES["unknown"])
    return (
        f'<span class="badge" style="background:{color}" title="{esc(tooltip)}">'
        f"{esc(label)}</span>"
    )


def normalize_badge(metrics: dict) -> str:
    """A satisfaction problem can never be 'valid and optimal': the objective
    check passes trivially, so re-label such verdicts as plain 'solution valid'."""
    badge = metrics.get("verdict", {}).get("badge", "unknown")
    if badge == "solution_valid_and_optimal" and not metrics.get("is_optimization"):
        return "solution_valid"
    return badge



def instance_label(identifier) -> tuple:
    """Name an evaluator instance the way the Instances section above does.

    That section numbers the problem's JSON rows from 1 and calls the first one
    the example; the corpus guarantees row 0 is exactly the embedded example. The
    evaluator instead identifies rows by their original index, so json:k is
    Instance k+1, and rows that duplicate an earlier one are skipped entirely.
    Returns the label plus the raw identifier, which is worth a tooltip rather
    than space on the page: it only matters when replaying an evaluation.
    """
    text = str(identifier)
    if identifier == "example":
        return "Example (Instance 1)", text
    if text.startswith("json:"):
        try:
            return f"Instance {int(text.split(':', 1)[1]) + 1}", text
        except ValueError:
            pass
    return text, ""


def evaluation_details(metrics: dict) -> str:
    """The specifics behind the verdict, collapsed so the badge stays the headline."""
    record = metrics.get("evaluation") or {}
    instances = record.get("instances") or []
    if not instances:
        return ""
    requested, limits = record.get("requested") or {}, record.get("limits") or {}
    rows = []
    for item in instances:
        label, raw = instance_label(item.get("id"))
        received, distinct = item.get("solutions_received"), item.get("solutions_checked")
        status = (item.get("runner_status") or {}).get("status") or "did not run"
        if item.get("accepted"):
            outcome, css = "accepted", "yes"
        elif item.get("skipped"):
            outcome, css = f"skipped, {item.get('reason', '')}", "no"
        else:
            outcome, css = item.get("reason") or "failed", "no"
        seconds = item.get("execution_wall_seconds")
        rows.append(
            f'<tr><td class="cell-id" title="{esc(raw)}">{esc(label)}</td>'
            f'<td>{"&mdash;" if received is None else received}</td>'
            f'<td>{"&mdash;" if distinct is None else distinct}</td>'
            f'<td>{esc(status)}</td>'
            f'<td class="cell-cat {css}">{esc(outcome)}</td>'
            f'<td>{"&mdash;" if seconds is None else f"{seconds:.1f}&thinsp;s"}</td></tr>'
        )
    skipped = record.get("skipped_instances") or []
    headline = (f'Verified {record.get("instances_checked")} of '
                f'{record.get("instances_available")} distinct instances, accepting '
                f'{record.get("solutions_checked")} solutions in total')
    if skipped:
        headline += f", with {len(skipped)} instance(s) skipped as inconclusive"
    asked = (f'Asked for up to {requested.get("solution_limit")} distinct solution(s) on up to '
             f'{requested.get("instance_count")} instances, bounded at '
             f'{limits.get("execution_timeout")}&thinsp;s solving, '
             f'{limits.get("reference_timeout")}&thinsp;s reference, '
             f'{limits.get("memory_mb")}&thinsp;MiB, {limits.get("cpus")}&thinsp;CPU.')
    return (
        '<details class="instance" style="margin-top:8px">'
        '<summary>Evaluation detail</summary>'
        f'<div style="padding:10px 12px"><p class="desc" style="margin:0 0 8px">{headline}.</p>'
        '<table class="matrix"><thead><tr><th>Instance</th><th>Emitted</th><th>Distinct</th>'
        '<th>Runner</th><th>Outcome</th><th>Solve</th></tr></thead>'
        f'<tbody>{"".join(rows)}</tbody></table>'
        f'<p class="desc" style="margin:8px 0 0">{asked}</p></div></details>'
    )


def generated_model_html(entry: dict) -> str:
    """Render a generated model with the reference model's Metadata + Model layout."""
    metrics = entry["metrics"]
    generated_by = metrics.get("generated_by", {})
    uid = f"{metrics.get('problem', '')}-{entry['submission']}"

    rows = [
        f"<dt>Submission</dt><dd>{esc(entry['submission'])}</dd>",
        f"<dt>Base LLM</dt><dd>{esc(generated_by.get('base_llm') or 'Unknown')}</dd>",
    ]
    if generated_by.get("dataset_version"):
        rows.append(
            f"<dt>Dataset version</dt><dd>{esc(generated_by['dataset_version'])}</dd>"
        )
    chips = paradigm_chips(metrics.get("solver"), "../")
    if chips:
        rows.append(f"<dt>Paradigm</dt><dd>{chips}</dd>")
    rows.append(f"<dt>Evaluation</dt><dd>{verdict_badge(metrics)}"
                f"{evaluation_details(metrics)}</dd>")

    links = []
    if entry["model_file"]:
        links.append(
            f'<a href="{REPO_URL}/blob/main/generated_models/'
            f'{esc(metrics.get("problem", ""))}/{esc(entry["directory"])}/'
            f'{esc(entry["submission"])}/{esc(entry["model_file"])}" target="_blank" '
            f'rel="noopener">Model file (GitHub)</a>'
        )
    if links:

        rows.append(f'<dt>Sources</dt><dd>{" &middot; ".join(links)}</dd>')

    if entry["model_file"]:
        lang = "minizinc" if entry["model_file"].endswith(".mzn") else "python"
        model = code_block(entry["code"], lang, copy_id=f"gmod-{uid}")
    else:
        model = '<p class="desc">Code file not found.</p>'

    return (
        f'<div class="card-box provenance"><h3>Metadata</h3><dl>{"".join(rows)}</dl></div>'
        f'<h3>Model</h3>{model}'
    )


VALID_BADGE_ORDER = [
    "solution_valid_and_optimal",
    "solution_valid_objective_unknown",
    "solution_valid",
    "solution_valid_not_optimal",
]


def select_best_generated(gen_by_fw: dict) -> dict:
    """Keep at most one generated model per framework: the best valid one
    (valid + optimal preferred for optimisation problems). Frameworks without
    a valid model are dropped."""
    out = {}
    for fw, entries in gen_by_fw.items():
        best, best_rank = None, None
        for entry in entries:
            metrics = entry["metrics"]
            badge = normalize_badge(metrics)
            if badge in VALID_BADGE_ORDER:
                rank = VALID_BADGE_ORDER.index(badge)
                if best is None or rank < best_rank:
                    best, best_rank = entry, rank
        if best is not None:
            out[fw] = best
    return out


