# Fibonacci even-valued terms: print the sum of all even-valued terms of the
# sequence 1, 2, 3, 5, ... that do not exceed four million (res).
import mip

LIMIT = 4000000
TERMS = 33          # indices 0..32; index 32 (5702887) is the first term above LIMIT
BIG = 2 * LIMIT     # every term with index below TERMS is at most 2 * LIMIT


def build(instance):
    model = mip.Model(solver_name="CBC")
    # CBC presolve can return a point that breaks a fresh no-good row added after a solve
    # (two new binaries summing to at least 1, both 0 in the returned point). Presolve off.
    model.preprocess = 0

    # The sequence: start with 1 and 2.
    f = [model.add_var(f"f_{i}", lb=0, ub=BIG, var_type=mip.INTEGER) for i in range(TERMS)]
    model += f[0] == 1
    model += f[1] == 2

    # Each new term in the Fibonacci sequence is generated by adding the previous two terms.
    for i in range(2, TERMS):
        model += f[i] == f[i - 1] + f[i - 2]

    # Parity: a term is even when its remainder r is 0, so f = 2 * h + r with r binary.
    h = [model.add_var(f"h_{i}", lb=0, ub=BIG, var_type=mip.INTEGER) for i in range(TERMS)]
    r = [model.add_var(f"r_{i}", var_type=mip.BINARY) for i in range(TERMS)]
    for i in range(TERMS):
        model += f[i] == 2 * h[i] + r[i]

    # A term does not exceed four million: le = 1 if and only if f <= LIMIT.
    le = [model.add_var(f"le_{i}", var_type=mip.BINARY) for i in range(TERMS)]
    for i in range(TERMS):
        model += f[i] <= LIMIT + BIG * (1 - le[i])
        model += f[i] >= (LIMIT + 1) - (LIMIT + 1) * le[i]

    # Sum the even-valued terms which do not exceed four million: ok = 1 if and only if
    # the term is even (r = 0) and does not exceed four million (le = 1).
    ok = [model.add_var(f"ok_{i}", var_type=mip.BINARY) for i in range(TERMS)]
    for i in range(TERMS):
        model += ok[i] <= 1 - r[i]
        model += ok[i] <= le[i]
        model += ok[i] >= le[i] - r[i]

    # The contribution of a term is the term when ok = 1, and 0 otherwise.
    c = [model.add_var(f"c_{i}", lb=0, ub=LIMIT, var_type=mip.INTEGER) for i in range(TERMS)]
    for i in range(TERMS):
        model += c[i] <= f[i]
        model += c[i] <= LIMIT * ok[i]
        model += c[i] >= f[i] - BIG * (1 - ok[i])

    # Print the sum of all the even-valued terms which do not exceed four million (res).
    res = model.add_var("res", lb=0, ub=TERMS * LIMIT, var_type=mip.INTEGER)
    model += res == mip.xsum(c)

    return model, {"res": res}
