# Four numbers: find three integers x (each between 1 and 10) such that every
# given number is a sum of a subset of x. Satisfaction problem.
import mip


def build(instance):
    numbers = instance["numbers"]
    n = len(numbers)  # how many numbers this instance gives (up to four)
    model = mip.Model(sense=mip.MINIMIZE, solver_name="CBC")

    # the three integers x, each between 1 and 10 (problem statement)
    x = [model.add_var(f"x_{i}", lb=1, ub=10, var_type=mip.INTEGER) for i in range(3)]

    # subsets of the three integers: the 7 non-empty subsets, as index sets
    subsets = [[i for i in range(3) if (s >> i) & 1] for s in range(1, 8)]

    # the largest subset sum is three times 10 (problem statement bound on x)
    big = 30

    for k in range(n):
        value = numbers[k]
        # z[s] = 1 if subset s is the one that generates the number
        z = [model.add_var(f"z_{k}_{s}", var_type=mip.BINARY) for s in range(len(subsets))]
        # w[s] = sum of x over subset s if chosen, else 0
        w = [model.add_var(f"w_{k}_{s}", lb=0, ub=big, var_type=mip.INTEGER)
             for s in range(len(subsets))]

        # each number is generated by exactly one subset of x
        model += mip.xsum(z) == 1

        for s, members in enumerate(subsets):
            total = mip.xsum(x[i] for i in members)
            # w[s] equals the subset sum when chosen, and 0 otherwise
            model += w[s] <= total
            model += w[s] <= big * z[s]
            model += w[s] >= total - big * (1 - z[s])

        # the chosen subset sums to the given number
        # (the number is generated by summing the subsets of the three integers)
        model += mip.xsum(w) == value

    return model, {"x": x}
