// Problem: fibonacci_even. Sum of the even-valued terms of the Fibonacci sequence
// 1, 2, 3, 5, 8, ... which do not exceed four million (res).

fn build(_inst: &Instance, m: &mut Model) -> Res<Out> {
    // The description fixes the bound: four million. The number of terms that do not exceed
    // the bound is computed from the bound alone, by generating the sequence from 1 and 2.
    // Every term after the last one generated exceeds the bound and is not summed.
    const LIMIT: i64 = 4_000_000;
    let mut terms: Vec<i64> = vec![1, 2];
    loop {
        let next = terms[terms.len() - 1] + terms[terms.len() - 2];
        if next > LIMIT {
            break;
        }
        terms.push(next);
    }
    let n = terms.len();
    // Bound on the result: the sum of all modelled terms.
    let total: i64 = terms.iter().sum();

    // Each new term in the Fibonacci sequence is generated by adding the previous two terms.
    // By starting with 1 and 2, the terms are 1, 2, 3, 5, 8, ...
    let f = m.new_int_decisions(n, 0..=LIMIT);
    m.linear(f[0]).eq(1).post()?;
    m.linear(f[1]).eq(2).post()?;
    for i in 2..n {
        m.linear(f[i] - f[i - 1] - f[i - 2]).eq(0).post()?;
    }

    // Print the sum of all the even-valued terms in the sequence which do not exceed four million.
    // Parity of each term: the term is 2 * half + rest with rest in 0..=1, and the term is even
    // exactly when rest is 0. The flag take is equivalent to the term being even.
    // A taken term contributes its value to the sum, any other term contributes 0.
    let mut parts = Vec::new();
    for i in 0..n {
        let half = m.new_int_decision(0..=LIMIT / 2);
        let rest = m.new_int_decision(0..=1);
        m.linear(f[i] - half * 2 - rest).eq(0).post()?;
        let even = rest.leq(0);
        let take = m.new_bool_decision();
        m.proposition(BoolFormula::Equiv(vec![
            BoolFormula::Atom(take),
            BoolFormula::Atom(even),
        ]))
        .post()?;
        let part = m.new_int_decision(0..=LIMIT);
        m.linear(part - f[i]).le(0).implied_by(take).post()?;
        m.linear(part - f[i]).ge(0).implied_by(take).post()?;
        m.linear(part).le(0).implied_by(!take).post()?;
        parts.push(part);
    }

    // The result is the sum of the even-valued terms.
    let res = m.new_int_decision(0..=total);
    m.linear(parts.iter().copied().sum::<IntLinearExp>()).eq(res).post()?;

    let mut out = Out::new();
    out.put("res", res);
    Ok(out)
}
