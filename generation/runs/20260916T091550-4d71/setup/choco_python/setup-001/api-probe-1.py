from pychoco.model import Model
m = Model("api")
ok, bad = [], []
def t(name, fn):
    try:
        fn(); ok.append(name)
    except Exception as e:
        bad.append(f"{name}: {type(e).__name__}: {e}")

x = m.intvar(0, 5, name="x"); y = m.intvar(0, 5, name="y"); z = m.intvar(0, 25, name="z")
b = m.boolvar(name="b")
vs = [m.intvar(0, 5, name=f"v{i}") for i in range(3)]

t("intvar(values)", lambda: m.intvar([1,3,7], name="dom"))
t("arithm 3", lambda: m.arithm(x, "<=", 5).post())
t("arithm 5", lambda: m.arithm(x, "+", y, "=", 5).post())
t("sum_", lambda: m.sum_(vs, "=", z).post())
t("scalar", lambda: m.scalar(vs, [1,2,3], "=", z).post())
t("all_different", lambda: m.all_different(vs).post())
t("all_different_except_0", lambda: m.all_different_except_0(vs).post())
t("all_equal", lambda: m.all_equal(vs).post())
t("element", lambda: m.element(x, vs, y).post())
t("element const", lambda: m.element(x, [4,5,6], y).post())
t("count", lambda: m.count(2, vs, z).post())
t("global_cardinality", lambda: m.global_cardinality(vs, [0,1], [m.intvar(0,3), m.intvar(0,3)], False).post())
t("among", lambda: m.among(m.intvar(0,3), vs, [1,2]).post())
t("absolute", lambda: m.absolute(z, x).post())
t("distance", lambda: m.distance(x, y, "=", z).post())
t("div", lambda: m.div(x, m.intvar(1,5), z).post())
t("mod", lambda: m.mod(x, 3, z).post())
t("times", lambda: m.times(x, y, z).post())
t("min_", lambda: m.min_(z, vs).post())
t("max_", lambda: m.max_(z, vs).post())
t("sort", lambda: m.sort(vs, [m.intvar(0,5) for _ in range(3)]).post())
t("circuit", lambda: m.circuit([m.intvar(0,2) for _ in range(3)]).post())
t("table", lambda: m.table(vs, [[0,1,2],[1,2,3]]).post())
t("lex_less", lambda: m.lex_less(vs, [m.intvar(0,5) for _ in range(3)]).post())
t("lex_less_eq", lambda: m.lex_less_eq(vs, [m.intvar(0,5) for _ in range(3)]).post())
t("increasing", lambda: m.increasing(vs, 0).post())
t("decreasing", lambda: m.decreasing(vs, 0).post())
t("diff_n", lambda: m.diff_n([m.intvar(0,5) for _ in range(2)],[m.intvar(0,5) for _ in range(2)],[m.intvar(1,2) for _ in range(2)],[m.intvar(1,2) for _ in range(2)], True).post())
t("not_", lambda: m.not_(m.arithm(x, "=", 3)).post())
t("and_", lambda: m.and_([m.arithm(x, ">=", 0), m.arithm(y, ">=", 0)]).post())
t("or_", lambda: m.or_([m.arithm(x, "=", 1), m.arithm(x, "=", 2)]).post())
t("reify", lambda: m.arithm(x, "=", 3).reify())
t("reify_with", lambda: m.arithm(y, "=", 3).reify_with(b))
t("cumulative", lambda: None)
print("OK:", len(ok))
for f in bad: print("FAIL", f)
