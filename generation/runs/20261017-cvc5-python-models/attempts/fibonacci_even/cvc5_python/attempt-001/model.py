# Problem: fibonacci_even
# Each new term of the Fibonacci-style sequence starting with 1 and 2 is the sum of the
# previous two terms. Print the sum of all the even-valued terms in the sequence which do
# not exceed four million (res).
import cvc5.pythonic as cz

LIMIT = 4000000
# The 32nd term (3524578) is the last one not above LIMIT; 40 terms cover every term up to it
# and beyond, so no term within the limit is left out.
N_TERMS = 40


def build(instance):
    f = [cz.Int(f"f{i}") for i in range(N_TERMS)]
    res = cz.Int("res")

    # Each new term in the Fibonacci sequence is generated by adding the previous two terms.
    # By starting with 1 and 2
    constraints = [f[0] == 1, f[1] == 2]
    constraints += [f[i] == f[i - 1] + f[i - 2] for i in range(2, N_TERMS)]

    # Print the sum of all the even-valued terms in the sequence which do not exceed four million (res).
    constraints.append(
        res == cz.Sum([cz.If(cz.And(f[i] <= LIMIT, f[i] % 2 == 0), f[i], 0) for i in range(N_TERMS)])
    )

    return constraints, {"res": res}
