import org.chocosolver.solver.Model;
import org.chocosolver.solver.variables.BoolVar;
import org.chocosolver.solver.variables.IntVar;
import dcp.Instance;
import dcp.Outputs;

// Four numbers: find three integers between 1 and 10 such that every given number
// (up to four distinct values between 1 and 10) is the sum of a nonempty subset of them.
public class Submission {
  public static void build(Instance inst, Model m, Outputs out) {
    int[] numbers = inst.getIntArray("numbers");  // the numbers to generate
    int k = numbers.length;

    // the three integers to find
    IntVar[] x = m.intVarArray("x", 3, 1, 10);

    // one variable per nonempty subset of x: sub[mask - 1] is the sum of the chosen integers
    IntVar[] sub = new IntVar[7];
    for (int mask = 1; mask <= 7; mask++) {
      int size = Integer.bitCount(mask);
      IntVar[] chosen = new IntVar[size];
      int idx = 0;
      for (int i = 0; i < 3; i++) if ((mask & (1 << i)) != 0) chosen[idx++] = x[i];
      sub[mask - 1] = m.intVar("subsetSum" + mask, 1, 30);
      if (size == 1) m.arithm(sub[mask - 1], "=", chosen[0]).post();
      else m.sum(chosen, "=", sub[mask - 1]).post();
    }

    // each given number is the sum of some nonempty subset of x
    for (int j = 0; j < k; j++) {
      BoolVar[] matches = new BoolVar[7];
      for (int s = 0; s < 7; s++)
        matches[s] = m.arithm(sub[s], "=", numbers[j]).reify();
      // numbers[j] is generated by at least one subset
      m.sum(matches, ">=", 1).post();
    }

    out.put("x", x);
  }
}
